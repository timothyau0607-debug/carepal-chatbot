/** 依使用者角色組小晴 system 全文，供 /api/chat 等使用。 */
export function xiaoqingSystemForRole(role: UserRole): string {
  switch (role) {
    case "family":
      return xiaoqingSystemFamily();
    case "patient":
      return xiaoqingSystemPatient();
    case "staff":
      return xiaoqingSystemStaff();
    default: {
      const _n: never = role;
      return _n;
    }
  }
}

