/** 左欄可切換的「使用者脈絡」：家屬／患者本人／醫護團隊 */
export const USER_ROLES = ["family", "patient", "staff"] as const;
export type UserRole = (typeof USER_ROLES)[number];

const ROLE_SET = new Set<string>(USER_ROLES);

export function isUserRole(s: string | undefined | null): s is UserRole {
  return s != null && ROLE_SET.has(s);
}

export function parseUserRole(
  s: string | null | undefined,
  fallback: UserRole = "family"
): UserRole {
  if (s && isUserRole(s)) return s;
  return fallback;
}

export const USER_ROLE_LABEL: Record<
  UserRole,
  { short: string; description: string }
> = {
  family: { short: "家屬", description: "照顧者／家屬" },
  patient: { short: "病者", description: "患者本人" },
  staff: { short: "醫護", description: "醫療、護理或專業照護團隊" },
};

